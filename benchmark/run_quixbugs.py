"""Run AutoFixAI on the QuixBugs benchmark and write QUIXBUGS_RESULTS.md.

    git clone https://github.com/jkoppel/QuixBugs.git
    python -m benchmark.run_quixbugs --root QuixBugs [--time-limit 60] [--only gcd]

Outcome per program:
  identical  - patch passes all tests AND is AST-identical to the reference fix
  plausible  - patch passes all tests but differs from the reference (may be correct, may overfit)
  failed     - no single-edit patch found within the budget
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

from benchmark import heldout

HERE = Path(__file__).resolve().parent


def discover(root: Path) -> list[str]:
    return sorted(p.stem[len("test_"):] for p in (root / "python_testcases").glob("test_*.py"))


def run_one(root: Path, name: str, time_limit: float) -> dict:
    try:
        proc = subprocess.run(
            [sys.executable, "-m", "benchmark.quixbugs_worker", str(root), name, str(time_limit)],
            capture_output=True, text=True, timeout=time_limit + 90, cwd=HERE.parent,
        )
        return json.loads(proc.stdout.strip().splitlines()[-1])
    except Exception as exc:  # worker crashed or timed out
        return {"name": name, "status": "error", "note": f"{type(exc).__name__}"}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--time-limit", type=float, default=60.0)
    ap.add_argument("--only", action="append", default=[])
    args = ap.parse_args()
    root = Path(args.root).resolve()

    names = args.only or discover(root)
    rows = []
    for n in names:
        r = run_one(root, n, args.time_limit)
        rows.append(r)
        print(f"{n:28s} {r.get('status'):10s} tried={r.get('tried', '-')}", flush=True)

    for r in rows:  # held-out check for every plausible (non-identical) patch
        if r["status"] == "plausible":
            reference = (root / "correct_python_programs" / f"{r['name']}.py").read_text()
            r["heldout"] = heldout.check(r["name"], r["patched"], reference, root)
        r.pop("patched", None)

    valid = [r for r in rows if r["status"] not in ("invalid", "error")]
    ident = [r for r in valid if r["status"] == "identical"]
    plaus = [r for r in valid if r["status"] in ("identical", "plausible")]
    base = [r for r in valid if r.get("baseline_pipeline_passes")]
    equiv = [r for r in valid if r["status"] == "plausible" and r["heldout"]["verdict"] == "equivalent"]
    overfit = [r for r in valid if r["status"] == "plausible" and r["heldout"]["verdict"] == "overfit"]
    unverified = [r for r in valid if r["status"] == "plausible" and r["heldout"]["verdict"] == "unverified"]
    correct = len(ident) + len(equiv)

    lines = [
        "# QuixBugs results",
        "",
        "Independent benchmark: 40 classic algorithms with one-line bugs and a pytest suite each",
        "(Lin et al., *QuixBugs*, SPLASH Companion 2017).  Generated by `python -m benchmark.run_quixbugs`.",
        "",
        f"* Programs evaluated: **{len(valid)}**",
        f"* Baseline (v0.3 rule-based pipeline, no mutation search): **{len(base)}** fixed",
        f"* **Plausible** patches (all tests pass): **{len(plaus)}** ({len(plaus) / max(1, len(valid)):.0%})",
        f"* &nbsp;&nbsp;- **Identical** to the reference fix (AST-equal): **{len(ident)}**",
        f"* &nbsp;&nbsp;- Different from the reference but **equivalent on {heldout.N_INPUTS} held-out random inputs**: **{len(equiv)}**",
        f"* &nbsp;&nbsp;- **Overfit** (pass the tests, diverge on held-out inputs): **{len(overfit)}**",
        f"* &nbsp;&nbsp;- Plausible but unverifiable (no input generator): **{len(unverified)}**",
        f"* **Correct repairs: {correct} of {len(valid)} ({correct / max(1, len(valid)):.0%})**",
        "",
        "Method: spectrum-based fault localisation (Ochiai) ranks lines; generic first-order mutation",
        "operators are tried in that order; the first mutant passing every test is returned.",
        "No operator or ranking rule refers to any QuixBugs program.",
        "",
        "| Program | Result | Held-out check | Candidates tried | Patch |",
        "|---|---|---|---:|---|",
    ]
    for r in rows:
        h = r.get("heldout")
        held = f"{h['verdict']} ({h['agree']}/{h['total']})" if h and h["total"] else (h["verdict"] if h else "-")
        lines.append(f"| {r['name']} | {r['status']} | {held} | {r.get('tried', '-')} | {r.get('patch', r.get('note', ''))} |")
    lines += [
        "",
        "## Reading these numbers",
        "",
        "* Tests are the only specification, so *plausible* does not imply *correct*. The *identical* column is the",
        "  conservative figure; a plausible-but-different patch needs manual review.",
        "* Only single-edit repairs are searched. Bugs that need a missing statement, several edits, or a new",
        "  algorithmic idea are out of reach by design.",
        "* \"Equivalent on held-out inputs\" is strong evidence, not a proof.",
        "* **Contamination caveat:** the operator set was designed by someone who knows the typical QuixBugs bug",
        "  categories, and the argument-swap operator was added after the `gcd` program failed without it.",
        "  Treat the figure as an upper-bound-ish estimate for this operator set, not as performance on unseen bugs.",
    ]
    (HERE / "QUIXBUGS_RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (HERE / "quixbugs_results.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    print("\n".join(lines[:16]))


if __name__ == "__main__":
    main()
