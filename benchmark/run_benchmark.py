"""Run the benchmark and write RESULTS.md / results.json.

Usage:  python -m benchmark.run_benchmark
"""

from __future__ import annotations

import json
import time
from collections import OrderedDict
from pathlib import Path

from autofixai import analyze, repair
from autofixai.sandbox import run_code

from .cases import CASES, CONTROLS

HERE = Path(__file__).resolve().parent
TIMEOUT = 2.0


def validate_corpus() -> None:
    """Every reference must run cleanly and be free of static issues, or the benchmark is broken."""
    for case in CASES + CONTROLS:
        ref = run_code(case.reference, TIMEOUT)
        if not ref.passed:
            raise SystemExit(f"[corpus error] reference for {case.id} fails: {ref.summary()}")
        if analyze(case.reference):
            raise SystemExit(f"[corpus error] reference for {case.id} has static issues")


def evaluate_case(case) -> dict:
    oracle = run_code(case.reference, TIMEOUT).stdout
    t0 = time.perf_counter()
    report = repair(case.buggy, timeout=TIMEOUT)
    elapsed = time.perf_counter() - t0
    runs = bool(report.final_run and report.final_run.passed)
    matches = runs and report.final_run.stdout == oracle
    clean = not report.remaining_issues
    return {
        "id": case.id,
        "category": case.category,
        "runs": runs,
        "output_matches": matches,
        "correct": bool(matches and clean),
        "fixes": [f.rule for f in report.fixes],
        "rounds": report.rounds,
        "seconds": round(elapsed, 2),
    }


def evaluate_control(case) -> dict:
    report = repair(case.buggy, timeout=TIMEOUT)
    return {"id": case.id, "unchanged": not report.changed, "runs": bool(report.final_run and report.final_run.passed)}


def main() -> None:
    validate_corpus()
    rows = [evaluate_case(c) for c in CASES]
    controls = [evaluate_control(c) for c in CONTROLS]

    by_cat: OrderedDict[str, list[dict]] = OrderedDict()
    for r in rows:
        by_cat.setdefault(r["category"], []).append(r)

    in_scope = [r for r in rows if r["category"] != "unsupported"]
    baseline_ok = 0
    for c in CASES:
        if c.category == "unsupported":
            continue
        rep = repair(c.buggy, timeout=TIMEOUT, fixers=[])
        oracle = run_code(c.reference, TIMEOUT).stdout
        baseline_ok += bool(rep.final_run and rep.final_run.passed and rep.final_run.stdout == oracle and not rep.remaining_issues)
    total, ok = len(rows), sum(r["correct"] for r in rows)
    s_total, s_ok = len(in_scope), sum(r["correct"] for r in in_scope)
    runs_ok = sum(r["runs"] for r in rows)
    fp = sum(not c["unchanged"] for c in controls)
    avg_time = sum(r["seconds"] for r in rows) / len(rows)

    lines = [
        "# Benchmark results",
        "",
        "Generated by `python -m benchmark.run_benchmark`. See `benchmark/cases.py` for the corpus and its caveats.",
        "",
        "A repair is **correct** when the program runs, prints exactly what the reference solution prints, and no static issues remain.",
        "",
        "| Category | Cases | Runs | Correct |",
        "|---|---:|---:|---:|",
    ]
    for cat, rs in by_cat.items():
        lines.append(f"| {cat} | {len(rs)} | {sum(r['runs'] for r in rs)} | {sum(r['correct'] for r in rs)} |")
    lines += [
        f"| **In-scope total** | **{s_total}** | **{sum(r['runs'] for r in in_scope)}** | **{s_ok}** ({s_ok / s_total:.0%}) |",
        f"| **Overall (incl. unsupported)** | **{total}** | **{runs_ok}** | **{ok}** ({ok / total:.0%}) |",
        "",
        f"**Baseline (same pipeline, all fixers disabled):** {baseline_ok} of {s_total} in-scope cases correct.",
        f"**False positives on already-correct programs:** {fp} of {len(controls)} controls were modified.",
        f"**Mean repair time:** {avg_time:.2f}s per case (includes sandboxed re-runs).",
        "",
        "## Failures / limitations",
        "",
    ]
    failed = [r for r in rows if not r["correct"]]
    if failed:
        lines += ["| Case | Category | Runs | Output matches |", "|---|---|:-:|:-:|"]
        lines += [f"| {r['id']} | {r['category']} | {'yes' if r['runs'] else 'no'} | {'yes' if r['output_matches'] else 'no'} |" for r in failed]
    else:
        lines.append("None.")
    lines += [
        "",
        "Cases prefixed `UNSUP-` are bug classes the tool deliberately does not claim to fix.",
        "For guard cases (zero division, missing key) the reference accepts `None` as the result.",
    ]

    (HERE / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (HERE / "results.json").write_text(
        json.dumps({"cases": rows, "controls": controls}, indent=2), encoding="utf-8"
    )
    print("\n".join(lines))


if __name__ == "__main__":
    main()
